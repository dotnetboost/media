namespace DotNetBoost.Media.Core.Models;

/// <summary>
/// The stored record of one uploaded file: everything about it except the bytes, which live in
/// whichever backend <see cref="StorageProvider"/> names, at <see cref="StoragePath"/>.
/// A single table of these rows backs every upload in the system, whatever it is attached to —
/// adding media to a new entity adds no tables, no columns and no migrations.
/// <para>
/// The row is the source of truth about a file; the backend only holds bytes. That is what lets
/// the same library serve a file from local disk in development and from Azure or S3 in
/// production, move an existing file between backends, and answer "what is this, how big, who
/// uploaded it, what is it attached to" without ever touching the storage account.
/// </para>
/// <para>
/// Not sealed, on purpose: it is an entity type in the application's own context, and EF Core's
/// lazy-loading proxies refuse a model that contains a sealed entity type.
/// </para>
/// </summary>
public class MediaFile
{
    /// <summary>
    /// The file's identity, and the only handle the rest of the application needs. A GUID rather
    /// than a sequence: it is assigned before the bytes are written, so the storage path can be
    /// derived from it, and it is safe to put in a URL — it leaks neither an upload count nor
    /// another tenant's id.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// The name the file was uploaded under, e.g. <c>invoice-2026-09.pdf</c>. Kept for the
    /// download's <c>Content-Disposition</c> and for display; it is NOT the stored path, so two
    /// uploads of the same name never collide. Sanitised on upload — no directory separators,
    /// no control characters.
    /// </summary>
    public string FileName { get; set; } = string.Empty;

    /// <summary>
    /// The media type served back, e.g. <c>image/png</c>. Taken from the upload when it is
    /// plausible and from the file's own bytes when it is not — see
    /// <c>MediaOptions.VerifyContentType</c>.
    /// </summary>
    public string ContentType { get; set; } = string.Empty;

    /// <summary>Size of the stored bytes. Measured while writing, never taken on trust from the caller.</summary>
    public long Size { get; set; }

    /// <summary>
    /// Which backend holds the bytes: the <c>IMediaStorageProvider.Name</c> of the provider that
    /// wrote them (<c>FileSystem</c>, <c>AzureBlobStorage</c>, <c>AmazonS3</c>, or your own).
    /// Stored per file rather than read from configuration, so files uploaded before a backend
    /// change are still found afterwards.
    /// </summary>
    public string StorageProvider { get; set; } = string.Empty;

    /// <summary>
    /// The container the bytes are in, as that backend names one: the root directory on local
    /// disk, the blob container on Azure, the bucket on S3.
    /// </summary>
    public string StorageContainer { get; set; } = string.Empty;

    /// <summary>
    /// <b>The path to the file</b> inside <see cref="StorageContainer"/>, always with forward
    /// slashes: <c>images/2026/09/27/9f1c….png</c>. This — with the provider and container — is
    /// what the bytes are fetched by. Generated by <see cref="Interfaces.IMediaKeyGenerator"/>,
    /// never by the uploader, so an upload cannot choose where it lands or escape the container.
    /// </summary>
    public string StoragePath { get; set; } = string.Empty;

    /// <summary>
    /// Lowercase hex SHA-256 of the stored bytes, or <c>null</c> when
    /// <c>MediaOptions.ComputeChecksum</c> is off. Detects corruption, and backs the optional
    /// deduplication that returns the existing file instead of storing identical bytes twice.
    /// </summary>
    public string? Checksum { get; set; }

    /// <summary>
    /// Logical name of the entity type this file is attached to, e.g. <c>Product</c>, or
    /// <c>null</c> for a file that stands alone. Set by <c>IMediaManager.For(entity)</c>.
    /// </summary>
    public string? OwnerEntityName { get; set; }

    /// <summary>
    /// The owning entity's primary key, stored as a string so the same table serves <c>int</c>,
    /// <c>long</c>, <c>Guid</c> and <c>string</c> keys without a schema change. Formatted
    /// invariantly by <see cref="Metadata.EntityKey.ToKeyString"/>.
    /// </summary>
    public string? OwnerEntityId { get; set; }

    /// <summary>
    /// A coarse bucket the application sorts uploads into — <c>avatars</c>, <c>invoices</c>,
    /// <c>product-images</c>. Leads the generated <see cref="StoragePath"/>, so it is also how
    /// the files are laid out in the backend.
    /// </summary>
    public string? Category { get; set; }

    /// <summary>
    /// Free-form labels, stored comma-delimited AND comma-surrounded — <c>,invoice,2026,paid,</c>
    /// — so that a <c>LIKE '%,invoice,%'</c> matches a whole tag and never a prefix of another
    /// one. Read it through <see cref="MediaFileInfo.Tags"/> rather than parsing it here.
    /// </summary>
    public string? Tags { get; set; }

    /// <summary>
    /// Whatever else the application wants to keep with the file — image dimensions, a page
    /// count, the originating request — as a flat JSON object of strings. Opaque to this library
    /// apart from being read back into <see cref="MediaFileInfo.Metadata"/>.
    /// </summary>
    public string? Metadata { get; set; }

    /// <summary>Who uploaded it, as the application identifies people. Never inferred.</summary>
    public string? UploadedBy { get; set; }

    /// <summary>
    /// When the row was created, from the engine's <see cref="TimeProvider"/>.
    /// <para>
    /// <b>Always UTC.</b> A <see cref="DateTime"/> rather than a <see cref="DateTimeOffset"/>
    /// because every value here is UTC by construction, so an offset would be a zero carried
    /// through four storage engines for nothing — and SQLite cannot sort or compare a
    /// <c>DateTimeOffset</c> at all, which would make "newest first" a client-side operation on
    /// one of the engines this library supports.
    /// </para>
    /// </summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>When its metadata last changed, or <c>null</c> if it never has. UTC.</summary>
    public DateTime? UpdatedAt { get; set; }

    /// <summary>
    /// When it was deleted, or <c>null</c> while it is live. Set instead of removing the row when
    /// <c>MediaOptions.SoftDelete</c> is on — the bytes still go, so a soft-deleted row is a
    /// record that the file existed, not a way to get it back.
    /// </summary>
    public DateTime? DeletedAt { get; set; }

    /// <summary>True while the file has not been deleted.</summary>
    public bool IsDeleted => DeletedAt is not null;
}
